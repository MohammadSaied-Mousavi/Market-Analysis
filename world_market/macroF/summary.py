def _render_text_blocks_html(blocks) -> str:
    base_style = "direction: rtl; text-align: right; line-height: 2.1; font-size: 15px; font-family: Tahoma, Arial, sans-serif;"
    p_style = "margin: 0 0 14px 0;"
    h4_style = "margin-top: 22px; margin-bottom: 10px;"
    li_style = "margin-bottom: 10px;"
    ul_style = "margin: 0 0 14px 0; padding-right: 22px;"
    hr_style = "border: none; border-top: 1px solid rgba(255,255,255,0.15); margin: 18px 0;"

    parts = [f'<div style="{base_style}">']
    for block in blocks:
        kind = block[0]
        if kind == "h3":
            parts.append(f'<h3 style="margin-top:0;margin-bottom:14px;">{block[1]}</h3>')
        elif kind == "h4":
            parts.append(f'<h4 style="{h4_style}">{block[1]}</h4>')
        elif kind == "p":
            parts.append(f'<p style="{p_style}">{block[1]}</p>')
        elif kind == "ul":
            items = "".join(f'<li style="{li_style}">{item}</li>' for item in block[1])
            parts.append(f'<ul style="{ul_style}">{items}</ul>')
        elif kind == "hr":
            parts.append(f'<hr style="{hr_style}">')
    parts.append("</div>")
    return "".join(parts)


